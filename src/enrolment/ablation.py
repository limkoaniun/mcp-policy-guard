"""Deriving an ablated policy pack.

Specification §7 asks for "each policy turned off in turn". The pack is
already the single source of truth for which policies the engine loads, so an
ablation needs no new mechanism: it is the same pack with one name removed.

Derived rather than hand-written. A hand-copied ablation pack is free to drift
from the pack the baseline ran under -- a different upstream, a different
students file -- and then the two campaigns differ by more than the policy
under test, which is the one thing an ablation may not do.

Three of the four policies exist. `limits` is a stub, so a sweep produces
three ablations and the report must say why not four.
"""

from __future__ import annotations

from pathlib import Path

import yaml


def ablated_pack(pack_path, policy: str, out_dir) -> Path:
    """Write a copy of `pack_path` with `policy` removed, and return its path.

    Raises rather than producing a pack that would misreport what it ran:
    a policy the pack never loaded would yield a byte-equivalent baseline
    labelled as an ablation, and removing the last policy would yield an
    engine that allows every call while logging verdicts that look like
    enforcement -- the failure `policy_guard.__main__` already refuses, caught
    here where the ablation that caused it can be named.
    """
    pack_path = Path(pack_path)
    body = yaml.safe_load(pack_path.read_text(encoding="utf-8")) or {}
    policies = list(body.get("policies") or [])

    if policy not in policies:
        raise ValueError(
            f"cannot ablate {policy!r}: pack {pack_path.name} loads "
            f"{policies or 'no policies'}. An ablation of a policy the "
            f"baseline never ran is the baseline, reported under another name."
        )

    remaining = [name for name in policies if name != policy]
    if not remaining:
        raise ValueError(
            f"cannot ablate {policy!r}: it is the last policy {pack_path.name} "
            f"loads, and an enforcement-on run with no policies forwards every "
            f"call while writing verdicts that look like enforcement. Run the "
            f"enforcement-off arm instead -- that is what it measures."
        )

    body["policies"] = remaining
    # The manifest records the pack's name, so the name is what tells an
    # ablation apart from its baseline in `metrics.json`.
    body["name"] = f"{body.get('name', pack_path.stem)}-no-{policy}"

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    derived = out_dir / f"{pack_path.stem}-no-{policy}.yaml"
    derived.write_text(
        "# Generated by `enrolment.ablation.ablated_pack`. Do not edit: it is\n"
        f"# {pack_path.name} with the {policy!r} policy removed, and is\n"
        "# rewritten from that pack every time the ablation runs.\n"
        + yaml.safe_dump(body, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    return derived
